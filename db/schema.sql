-- ============================================
-- Clinica Azul Dashboard — Schema (demo / reconstruction)
-- Anonymized structure — no real patient data.
--
-- Note: the original project (clinic, spreadsheet, and dashboard) was run
-- in Spanish, as the clinic is based in Barcelona. For this public portfolio
-- reconstruction, all labels, seed data, and documentation have been
-- translated to English — the "Clinica Azul" name is kept as the brand
-- identity of the demo clinic.
-- ============================================

CREATE TABLE IF NOT EXISTS staff (
    staff_id      INT PRIMARY KEY AUTO_INCREMENT,
    full_name     VARCHAR(120) NOT NULL,
    role          VARCHAR(60)  NOT NULL,        -- e.g. 'Dentist', 'Hygienist', 'Receptionist'
    weekly_hours  INT          NOT NULL DEFAULT 40
);

CREATE TABLE IF NOT EXISTS patients (
    patient_id    INT PRIMARY KEY AUTO_INCREMENT,
    patient_code  VARCHAR(20)  NOT NULL UNIQUE, -- anonymized reference (e.g. 'PAT-0001')
    first_name    VARCHAR(60)  NOT NULL,        -- fictional — for display purposes only
    last_name     VARCHAR(60)  NOT NULL,        -- fictional — for display purposes only
    age_range     VARCHAR(10)  NOT NULL,        -- e.g. '18-30' — no birthdate stored
    created_at    DATE         NOT NULL
);

CREATE TABLE IF NOT EXISTS appointments (
    appointment_id   INT PRIMARY KEY AUTO_INCREMENT,
    patient_id       INT NOT NULL,
    staff_id         INT NOT NULL,
    scheduled_at     DATETIME NOT NULL,
    service_type     VARCHAR(80) NOT NULL,      -- e.g. 'Check-up', 'Cleaning', 'Treatment'
    status           ENUM('scheduled', 'attended', 'no_show', 'cancelled') NOT NULL DEFAULT 'scheduled',
    reminder_sent_at DATETIME NULL,
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    FOREIGN KEY (staff_id) REFERENCES staff(staff_id)
);

CREATE TABLE IF NOT EXISTS satisfaction_surveys (
    survey_id       INT PRIMARY KEY AUTO_INCREMENT,
    appointment_id  INT NOT NULL,
    score           TINYINT NOT NULL,           -- 1-5
    comment         TEXT NULL,
    sentiment       ENUM('positive', 'neutral', 'negative') NULL,
    sentiment_score DECIMAL(4,3) NULL,          -- -1.0 to 1.0, filled by the n8n sentiment workflow
    submitted_at    DATETIME NOT NULL,
    FOREIGN KEY (appointment_id) REFERENCES appointments(appointment_id)
);

